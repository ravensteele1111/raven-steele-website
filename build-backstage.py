def write_sets():
    """One page per set of photographs that has actually arrived."""
    index = os.path.join(HERE, "assets", "backstage", "index.json")
    if not os.path.exists(index):
        return {}
    sets = json.load(io.open(index, encoding="utf-8"))

    foot = io.open(os.path.join(HERE, "_backstage-template.html"),
                   encoding="utf-8").read()
    foot = foot[foot.index("<footer"):foot.index("</footer>") + len("</footer>")]

    done = {}
    for slug, info in sets.items():
        shots = info["shots"]
        thumbs_only = info.get("thumbs_only")
        rows = []
        for n in shots:
            if thumbs_only:
                # Nothing bigger was kept, so tapping opens the same picture.
                big = "assets/backstage/%s/%s-sm.webp" % (slug, n)
            else:
                big = "assets/backstage/%s/%s.webp" % (slug, n)
            thumb = "assets/backstage/%s/%s-sm.webp" % (slug, n)
            # The first dozen carry their picture in the markup so the top of
            # the page is never empty. The rest are fetched as they come into
            # view.
            #
            # An <img> would get this free with loading="lazy". A background
            # picture does not, and swapping one for the other to make them
            # unsaveable quietly threw lazy loading away: fifty thumbnails
            # began downloading at once and tiles sat blank until they
            # arrived. That is what Blue saw on the 90s Party page.
            if len(rows) < 12:
                rows.append('        <button data-big="%s" '
                            'style="background-image:url(%s)" '
                            'aria-label="Open photograph"></button>'
                            % (big, thumb))
            else:
                rows.append('        <button data-big="%s" data-thumb="%s" '
                            'aria-label="Open photograph"></button>'
                            % (big, thumb))
        page = SET_SHELL % {"name": esc(info["name"]), "count": len(shots),
                            "grid": "\n".join(rows), "foot": foot}
        io.open(os.path.join(HERE, "backstage-%s" % slug), "w",
                encoding="utf-8").write(page)
        done[slug] = len(shots)
        print("  backstage-%s.html: %d photographs" % (slug, len(shots)))
    return done


def tile(item, kind="event"):
    ready = item.get("ready")
    name = esc(item["name"])
    note = esc(item.get("note", ""))
    count = item.get("count")
    if count:
        note = note + (". " if note else "") + "%d photographs" % count

    if ready and item.get("href"):
        return ('        <a class="vault" href="%s">\n'
                '          <span class="vault-name">%s</span>\n'
                '          <span class="vault-note">%s</span>\n'
                '          <span class="vault-go">Open</span>\n'
                '        </a>' % (esc(item["href"]), name, note))

    return ('        <div class="vault" data-soon="true">\n'
            '          <span class="vault-name">%s</span>\n'
            '          <span class="vault-note">%s</span>\n'
            '          <span class="vault-go">Coming soon</span>\n'
            '        </div>' % (name, note))


def main():
    data = json.load(io.open(os.path.join(HERE, "backstage.json"), encoding="utf-8"))

    # What has actually been downloaded wins over what the file claims, so a
    # set cannot say "coming soon" while its photographs sit right there, and
    # cannot link to a page that was never written.
    live = write_sets()
    for e in data["events"]:
        if e["slug"] in live:
            e["ready"] = True
            e["href"] = "backstage-%s" % e["slug"]
            e["count"] = live[e["slug"]]

    events = "\n".join(tile(e) for e in data["events"])
    extras = "\n".join(tile(e) for e in data["extras"])
    ready = sum(1 for e in data["events"] + data["extras"] if e.get("ready"))

    page = io.open(os.path.join(HERE, "_backstage-template.html"), encoding="utf-8").read()
    page = (page.replace("%%EVENTS%%", events)
                .replace("%%EXTRAS%%", extras)
                .replace("%%COUNT%%", str(len(data["events"]))))
    io.open(os.path.join(HERE, "backstage.html"), "w", encoding="utf-8").write(page)

    print("backstage.html: %d events, %d extras, %d of them ready"
          % (len(data["events"]), len(data["extras"]), ready))
    if not ready:
        print("   nothing is live behind it yet, so every tile says coming soon.")
        print("   That is deliberate: a tile that says soon is honest, a tile that")
        print("   links nowhere is a broken promise to somebody who just joined.")


if __name__ == "__main__":
    main()
