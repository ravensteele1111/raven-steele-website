"""
Build the event pages from events.json.

One event page looks exactly like every other event page, so writing them by
hand would be forty chances to make a typo. Add an event to events.json and
run this:

    python build-events.py
    python stamp.py

It writes one event-<slug>.html per event, and rewrites the list of events on
events.html between the two EVENTS markers.
"""

import io
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))

NAV = """  <nav class="site-nav" id="site-nav" data-open="false">
      <div class="wrap">
        <ul>
        <li><a href="index.html">Home</a></li>
        <li><a href="story.html">The Story</a></li>
        <li><a href="music.html">Music</a></li>
        <li><a href="events.html" aria-current="page">Events</a></li>
        <li><a href="be-like-raven.html">Be Like Raven</a></li>
        <li><a href="shop.html">Shop</a></li>
        </ul>
      </div>
    </nav>"""

FOOT = """<footer class="site-foot">
  <div class="wrap">
    <div class="socials">
      <a href="https://www.instagram.com/therealravenai" rel="noopener">Instagram</a>
      <a href="https://www.youtube.com/@Therealravenai" rel="noopener">YouTube</a>
    </div>
    <div class="legal">
      <a href="#">Privacy</a><a href="#">Terms</a><a href="#">Cookies</a>
    </div>
    <p class="copyright">&copy; 2026 Raven Steele</p>
  </div>
</footer>

<div class="pinned">
  <div class="wrap">
    <p>Get the pics first.</p>
    <a class="btn btn-primary" href="index.html#rebels">Join</a>
  </div>
</div>

<div class="lightbox" id="lightbox" data-open="false" role="dialog" aria-modal="true" aria-label="Photo">
  <button class="close" aria-label="Close">&times;</button>
  <div>
    <div class="ph"><span>Photo, full size</span></div>
    <p class="label"></p>
  </div>
</div>

</body>
</html>
"""

# Moods the customer asked for: Goofy, Sweet, and Action for the shots of
# people actually doing something at the party.
MOODS = ["sweet", "goofy", "action"]


def photo_grid(count):
    out = []
    for i in range(count):
        mood = MOODS[i % len(MOODS)]
        out.append(
            '        <button data-tag="%s" data-caption="Photo %d">'
            '<span class="ph ph-square"><span>Photo</span></span></button>'
            % (mood, i + 1)
        )
    return "\n".join(out)


def page(ev, nxt):
    story = ev.get("story") or "[WHAT HAPPENED: two lines telling the story of the night.]"
    date = ev.get("date", "")
    sub = ev.get("subtitle")

    guests = "\n".join(
        '        <span>%s</span>' % g for g in ev["guests"]
    )
    if not ev.get("guests_complete", False):
        guests += '\n        <span>[MORE GUESTS]</span>'

    return """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>%(name)s | Raven Steele</title>

<!-- GENERATED by build-events.py from events.json. Do not edit by hand:
     the next build will overwrite it. Change events.json instead. -->

<meta name="description" content="%(name)s. The night, and every photo from it.">
<meta name="theme-color" content="#000000">
<meta name="robots" content="noindex, nofollow">
<link rel="stylesheet" href="assets/css/site.css">
<script src="assets/js/site.js" defer></script>
</head>
<body>

<header class="site-head">
  <div class="wrap">
    <a class="logo" href="index.html">Raven Steele</a>
    <button class="menu-btn" aria-expanded="false" aria-controls="site-nav" aria-label="Menu">
      <span></span><span></span><span></span>
    </button>
  </div>
%(nav)s
</header>

<main>

  <section class="hero" style="padding-top:1.25rem">
    <div class="wrap">
      <a class="back" href="events.html">&larr; Back to all events</a>

      <div class="ph ph-wide" style="margin-bottom:1.25rem">
        <span>Group shot, full width</span>
      </div>

      %(datep)s
      <h2 style="margin-top:.3rem">%(name)s</h2>%(sub)s
      <p class="lede">%(story)s</p>
    </div>
  </section>

  <section class="alt">
    <div class="wrap">
      <div class="section-head">
        <p class="eyebrow">The guest list</p>
        <h2>Who was there</h2>
      </div>
      <div class="guests">
%(guests)s
      </div>
    </div>
  </section>

  <section>
    <div class="wrap">
      <div class="section-head">
        <p class="eyebrow">The night</p>
        <h2>Photos</h2>
      </div>

      <div class="filters" data-target="photos">
        <button class="chip" data-filter="all" aria-pressed="true">All</button>
        <button class="chip" data-filter="goofy" aria-pressed="false">Goofy</button>
        <button class="chip" data-filter="sweet" aria-pressed="false">Sweet</button>
        <button class="chip" data-filter="action" aria-pressed="false">Action</button>
      </div>

      <div class="photo-grid" id="photos">
%(photos)s
      </div>

      <p class="hint">Tap any photo to see it big and share it.</p>

      <div class="entry">
        <span class="btn btn-ghost" data-pending>Share event</span>
        <a class="btn btn-primary" href="event-%(next)s.html">Next event</a>
      </div>
    </div>
  </section>

</main>

%(foot)s""" % {
        "name": ev["name"],
        "nav": NAV,
        "datep": ('<p class="event-date">%s</p>' % date) if date else "",
        "sub": ('\n      <p class="lede" style="margin-top:.2rem"><em>%s</em></p>' % sub) if sub else "",
        "story": story,
        "guests": guests,
        "photos": photo_grid(ev.get("photos", 8)),
        "next": nxt,
        "foot": FOOT,
    }


def card(ev):
    date = ev.get("date", "")
    return """        <a class="event-card" href="event-%(slug)s.html"
           data-tag="%(year)s"
           data-event="%(name)s"
           data-guests="%(guests)s">
          <span class="ph ph-wide"><span>Best photo from this event</span></span>
          <span class="name" style="display:block">%(name)s</span>
          <span class="meta">%(meta)s</span>
        </a>""" % {
        "slug": ev["slug"],
        "year": ev["year"],
        "name": ev["name"],
        "guests": ", ".join(ev["guests"]),
        "meta": ("%s &middot; %s photos" % (date, ev.get("photos", 8))) if date else ("%s photos" % ev.get("photos", 8)),
    }


def main():
    os.chdir(HERE)
    data = json.load(io.open("events.json", encoding="utf-8"))
    events = data["events"]

    for i, ev in enumerate(events):
        nxt = events[(i + 1) % len(events)]["slug"]
        io.open("event-%s.html" % ev["slug"], "w", encoding="utf-8").write(page(ev, nxt))
        print("wrote event-%s.html" % ev["slug"])

    listing = "\n\n".join(card(ev) for ev in events)
    listing += '\n\n        <p class="empty" data-hidden="true">Nothing from that year yet.</p>'

    page_text = io.open("events.html", encoding="utf-8").read()
    new = re.sub(
        r"(<!-- EVENTS:START -->).*?(<!-- EVENTS:END -->)",
        lambda m: m.group(1) + "\n" + listing + "\n        " + m.group(2),
        page_text,
        flags=re.S,
    )
    if new == page_text:
        print("!! EVENTS markers not found in events.html — listing not updated")
    else:
        io.open("events.html", "w", encoding="utf-8").write(new)
        print("updated the listing on events.html")

    print("%d events" % len(events))


if __name__ == "__main__":
    main()
